const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('wwwroot/js/pet-battle.js','utf8');
const scope=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function petCastHitSchedule(')),scope);
const cast={turn:2,skill:'Linh thuật',dmg:60,hits:[10,20,30],heal:12,guard:15};
const schedule=scope.petCastHitSchedule(cast);
assert.equal(schedule.reduce((n,x)=>n+x.damage,0),60);
assert(schedule.every((x,i)=>x.at>=0&&x.at<=1&&(!i||x.at>schedule[i-1].at)));
const seen={},events=[],battle={pet:{casts:[cast]}};
for(let i=0;i<=100;i++)scope.petBattleFeedback(battle,{name:'fight',i:2,s:i/100,trip:1},seen,e=>events.push(e),10,20,100,80);
const hits=events.filter(e=>e.type==='num'&&e.text.startsWith('-'));
assert.equal(hits.length,3);assert.equal(hits.reduce((n,e)=>n-Number(e.text),0),60);
assert(hits.every(e=>e.source==='pet'&&e.x===100&&e.y===80));
assert.equal(events.filter(e=>e.text==='+12').length,1);
assert.equal(events.filter(e=>e.text==='Khiên +15').length,1);
const before=events.length;
scope.petBattleFeedback(battle,{name:'fight',i:2,s:1,trip:1},seen,e=>events.push(e),10,20,100,80);
assert.equal(events.length,before);
console.log('PASS pet hit timing, per-hit totals, target coordinates, support feedback and duplicate suppression.');
